const I18nContext = createContext(null);

const getLocaleForLanguage = (language) => {
  return language === 'EN' ? 'en-US' : 'pl-PL';
};

const getValueByKeyPath = (obj, keyPath) => {
  if (!obj) return undefined;
  const parts = String(keyPath || '').split('.').filter(Boolean);
  let current = obj;
  for (const part of parts) {
    if (current == null || typeof current !== 'object') return undefined;
    current = current[part];
  }
  return current;
};

const interpolate = (template, vars) => {
  if (typeof template !== 'string') return template;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key) => {
    if (Object.prototype.hasOwnProperty.call(vars, key)) {
      return String(vars[key] ?? '');
    }
    return match;
  });
};

export function I18nProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    if (typeof window === 'undefined') return 'PL';
    const stored = localStorage.getItem(STORAGE_KEY);
    return stored === 'EN' ? 'EN' : 'EN';
  });

  useEffect(() => {
    if (typeof window === 'undefined') return;
    localStorage.setItem(STORAGE_KEY, language);
  }, [language]);

  const toggleLanguage = useCallback(() => {
    setLanguage((prev) => (prev === 'PL' ? 'EN' : 'PL'));
  }, []);

  const t = useCallback(
    (key, vars) => {
      const fromLang = getValueByKeyPath(dictionaries[language], key);
      const fallback = getValueByKeyPath(dictionaries.PL, key);
      const value = fromLang ?? fallback;
      if (value == null) return String(key);
      return interpolate(value, vars);
    },
    [language],
  );

  const locale = useMemo(() => getLocaleForLanguage(language), [language]);

  const value = useMemo(
    () => ({
      language,
      setLanguage,
      toggleLanguage,
      t,
      locale,
    }),
    [language, toggleLanguage, t, locale],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    throw new Error('useI18n must be used within an I18nProvider');
  }
  return ctx;
}
